"""F: does the encounter conversation change the tour? (simulation only)

    python3 -m perception.encounter_sim.check [--seeds 20] [--out perception/encounter_sim/check.md]

Two conditions per seed, both with our encounter handoff (ids, clusters, age band, placeholders), the fake LLM (so it
can be rerun) and his tour code unchanged: "no layers" hands over without the conversation's pending layers;
"layers" hands them over. The seed changes who answers and our scene's jitter; his tour sim keeps its own seed.
Pressure on the reserved visitor (his H3) is proxied by robot actions toward v4 that are not routine: gaze_at v4 other
than gaze balancing / cue words, and additions whose score names v4. Routine gaze balancing toward v4 is counted apart.
Replies are truthful by construction (templates over hidden interests), so "layers" is a best case for the conversation.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from collections import Counter

from .llm import FakeLLM
from .run import run

ROUTINE = ("gaze balancing", "cue word")


def summary(recs, info):
    m = recs[-1]
    acts = [r for r in recs if r["type"] == "action" and r["t"] >= 0]
    v4 = [a for a in acts if a["args"].get("target") == "visitor:v4" and not a["reason"].startswith(ROUTINE)]
    v4 += [a for a in acts if a["kind"] == "say_to_group" and "(v4)" in a["reason"]]
    return {"route": " → ".join(r["stop"] for r in recs if r["type"] == "note" and r["note"] == "stop start"),
            "uptake": m["steering_uptake"]["share"], "misread": m["misread_rate"]["rate"] or 0.0,
            "p13": m["p13_unresolved"]["share"], "episodes": m["exclusion"]["episodes"],
            "v4 non-routine": len(v4),
            "v4 gaze balancing": sum(a["args"].get("target") == "visitor:v4" and a["reason"].startswith("gaze balancing")
                                     for a in acts),
            "layers": sum(len(v) for v in info["layers"].values())}


def run_all(n):
    out = {"no layers": [], "layers": []}
    for seed in range(1, n + 1):
        for cond in out:
            recs, _, info = run("s2_multi_stop", llm=FakeLLM(), seed=seed, pending=cond == "layers")
            out[cond].append(summary(recs, info))
        print(f"seed {seed}: done", file=sys.stderr)
    return out


def report(out, n):
    f = lambda xs: f"{statistics.mean(xs):.2f} [{min(xs):.2f}–{max(xs):.2f}]"
    keys = ["uptake", "misread", "p13", "episodes", "v4 non-routine", "v4 gaze balancing", "layers"]
    md = ["# Encounter check (F): the conversation's pending layers in s2_multi_stop (simulation only)", "",
          f"Generated by `python3 -m perception.encounter_sim.check --seeds {n}` (fake LLM, policy `ours`, seeds 1–{n}). "
          "See the module docstring for the conditions and the pressure proxy. Values are mean [min–max].", "",
          "| condition | " + " | ".join(keys) + " |", "|---" * (len(keys) + 1) + "|"]
    for c, rows in out.items():
        md.append(f"| {c} | " + " | ".join(f([r[k] for r in rows]) for k in keys) + " |")
    md += ["", "Route (stops) per condition:", ""]
    for c, rows in out.items():
        md += [f"- {c}: " + "; ".join(f"{r} ({k}/{n})" for r, k in Counter(r["route"] for r in rows).most_common())]
    md += ["", "Per seed (layers condition):", "", "| seed | layers | route | uptake | misread |", "|---|---|---|---|---|"]
    md += [f"| {i} | {r['layers']} | {r['route']} | {r['uptake']} | {r['misread']} |" for i, r in enumerate(out["layers"], 1)]
    return "\n".join(md) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    md = report(run_all(a.seeds), a.seeds)
    if a.out:
        open(a.out, "w").write(md)
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
